"""Download the frozen price history for every Hang Seng Index constituent (network).

    uv run python scripts/build_hsi_snapshot.py

Writes data/snapshot_hsi_<as_of>.parquet (95 constituents + ^HSI, same as_of as the core
snapshot) and portfolios/hsi.yaml: an HSI-weighted book of HKD 10m, shares = official index
weight x NAV / close on as_of. The 9-stock core snapshot is never touched.
"""

import sys

from hkrisk import PROJECT_ROOT
from hkrisk.data import SNAPSHOT_AS_OF, download_prices
from hkrisk.universe import HSI_SNAPSHOT_PATH, load_universe

NAV_HKD = 10_000_000

uni = load_universe()
tickers = [c["ticker"] for c in uni] + ["^HSI"]
df = download_prices(tickers, "2007-01-01", SNAPSHOT_AS_OF)
missing = [t for t in tickers if t not in df.columns or df[t].dropna().empty]
if missing:
    sys.exit(f"no data for {missing}; rerun later (Yahoo throttling) before freezing")
df.to_parquet(HSI_SNAPSHOT_PATH)
print(f"saved {HSI_SNAPSHOT_PATH} {df.shape}, {df.index[0].date()} to {df.index[-1].date()}")

last = df.loc[:SNAPSHOT_AS_OF].ffill().iloc[-1]
total_w = sum(c["weight_pct"] for c in uni)
lines = ["# HSI-weighted book: HKD 10m split by official index weights (universe/hsi_constituents.yaml),",
         f"# shares = weight x NAV / adjusted close on {SNAPSHOT_AS_OF}, rounded to whole shares.",
         "# Board lots are not enforced. Generated by scripts/build_hsi_snapshot.py.",
         "currency: HKD", "holdings:"]
for c in uni:
    shares = round(c["weight_pct"] / total_w * NAV_HKD / float(last[c["ticker"]]))
    lines.append(f'  "{c["ticker"]}": {max(shares, 1)}   # {c["name"]}')
(PROJECT_ROOT / "portfolios" / "hsi.yaml").write_text("\n".join(lines) + "\n")
first = df.drop(columns="^HSI").apply(lambda s: s.first_valid_index())
print("latest first-listing dates:\n", first.sort_values().tail(8))
