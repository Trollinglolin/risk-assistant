"""Locate crisis windows from ^HSI in the snapshot and write scenarios.yaml.

    uv run python scripts/find_scenarios.py
"""

import yaml

from hkrisk.data import load_snapshot
from hkrisk.stress import SCENARIOS_PATH, find_drawdown_window

SEARCH = {
    "gfc_2008": ("2008-09-01", "2008-11-30", "2008 GFC: Lehman collapse to the Oct-2008 low"),
    "covid_2020": ("2020-01-01", "2020-04-30", "2020 COVID crash: Jan peak to Mar low"),
    "china_tech_2022": ("2022-06-01", "2022-12-31",
                        "2022 HK/China tech selloff: Jun high to Oct-2022 low"),
}

hsi = load_snapshot()["^HSI"]
out = {}
for name, (a, b, desc) in SEARCH.items():
    w = find_drawdown_window(hsi, a, b)
    out[name] = {"start": w["peak"], "end": w["trough"], "description": desc,
                 "hsi_drawdown": round(w["drawdown"], 4), "search_window": [a, b]}
    print(name, w)

header = (
    "# Generated by scripts/find_scenarios.py from data/snapshot_*.parquet.\n"
    "# start/end = the largest peak-to-trough ^HSI drawdown inside search_window\n"
    "# (running max, then argmin of P/cummax - 1). Not hard-coded from memory.\n"
)
SCENARIOS_PATH.write_text(header + yaml.safe_dump({"scenarios": out}, sort_keys=False))
